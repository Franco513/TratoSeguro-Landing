-- TratoSeguro
-- Punto 10: una sola tabla para los inscritos a la beta.
-- La tabla se mantiene sin normalización para esta etapa académica.

create table if not exists public.registro_beta (
    id bigint generated by default as identity primary key,
    nombre varchar(100) not null,
    correo varchar(150) not null unique,
    perfil varchar(40) not null,
    empresa varchar(120),
    necesidad text not null,
    interes varchar(80) not null,
    fecha_inscripcion timestamptz not null default now()
);

-- Seguridad para el acceso desde la landing.
alter table public.registro_beta enable row level security;

-- Permitir que visitantes no autenticados registren su inscripción.
drop policy if exists "Permitir inscripcion beta anonima" on public.registro_beta;

create policy "Permitir inscripcion beta anonima"
on public.registro_beta
for insert
to anon
with check (true);

-- La landing no necesita leer los registros.
revoke select, update, delete on public.registro_beta from anon;

-- Permitir insertar registros desde el cliente público.
grant insert on public.registro_beta to anon;

-- Permitir que la secuencia de identidad genere nuevos IDs.
grant usage, select on sequence public.registro_beta_id_seq to anon;
